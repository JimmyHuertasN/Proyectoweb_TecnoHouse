-- =====================================================================
-- fotos_servicio.sql
-- Bucket privado y metadatos para imágenes adjuntas a servicios.
-- Ejecutar en Supabase → SQL Editor. Se puede volver a ejecutar sin duplicar políticas.
-- =====================================================================

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fotos-servicio', 'fotos-servicio', false, 3145728, array['image/jpeg', 'image/png'])
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.servicio_fotos (
    id bigint generated by default as identity primary key,
    servicio_id bigint not null references public.servicios(id) on delete cascade,
    ruta text not null unique,
    creado_en timestamptz not null default now()
);

alter table public.servicio_fotos enable row level security;
grant select, insert, delete on public.servicio_fotos to authenticated;
grant usage, select on sequence public.servicio_fotos_id_seq to authenticated;

drop policy if exists "servicio_fotos_select_participantes" on public.servicio_fotos;
create policy "servicio_fotos_select_participantes"
on public.servicio_fotos for select to authenticated
using (
    exists (
        select 1
        from public.servicios as servicio
        where servicio.id = servicio_fotos.servicio_id
          and (
              servicio.cliente_id = auth.uid()
              or servicio.tecnico_id = auth.uid()
              or public.rol_actual() = 'admin'
          )
    )
);

drop policy if exists "servicio_fotos_insert_dueno" on public.servicio_fotos;
create policy "servicio_fotos_insert_dueno"
on public.servicio_fotos for insert to authenticated
with check (
    ruta ~ ('^' || servicio_id::text || '/[^/]+$')
    and exists (
        select 1
        from public.servicios as servicio
        where servicio.id = servicio_fotos.servicio_id
          and servicio.cliente_id = auth.uid()
    )
);

drop policy if exists "servicio_fotos_delete_dueno" on public.servicio_fotos;
create policy "servicio_fotos_delete_dueno"
on public.servicio_fotos for delete to authenticated
using (
    exists (
        select 1
        from public.servicios as servicio
        where servicio.id = servicio_fotos.servicio_id
          and servicio.cliente_id = auth.uid()
    )
);

drop policy if exists "fotos_servicio_storage_select_participantes" on storage.objects;
create policy "fotos_servicio_storage_select_participantes"
on storage.objects for select to authenticated
using (
    bucket_id = 'fotos-servicio'
    and exists (
        select 1
        from public.servicio_fotos as foto
        join public.servicios as servicio on servicio.id = foto.servicio_id
        where foto.ruta = storage.objects.name
          and (
              servicio.cliente_id = auth.uid()
              or servicio.tecnico_id = auth.uid()
              or public.rol_actual() = 'admin'
          )
    )
);

drop policy if exists "fotos_servicio_storage_insert_dueno" on storage.objects;
create policy "fotos_servicio_storage_insert_dueno"
on storage.objects for insert to authenticated
with check (
    bucket_id = 'fotos-servicio'
    and (storage.foldername(name))[1] ~ '^[0-9]+$'
    and exists (
        select 1
        from public.servicios as servicio
        where servicio.id::text = (storage.foldername(name))[1]
          and servicio.cliente_id = auth.uid()
    )
);

drop policy if exists "fotos_servicio_storage_delete_dueno" on storage.objects;
create policy "fotos_servicio_storage_delete_dueno"
on storage.objects for delete to authenticated
using (
    bucket_id = 'fotos-servicio'
    and (storage.foldername(name))[1] ~ '^[0-9]+$'
    and exists (
        select 1
        from public.servicios as servicio
        where servicio.id::text = (storage.foldername(name))[1]
          and servicio.cliente_id = auth.uid()
    )
);

comment on table public.servicio_fotos is 'Rutas privadas de las imágenes adjuntas a solicitudes de servicio.';
