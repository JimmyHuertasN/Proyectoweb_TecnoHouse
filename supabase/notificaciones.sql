-- Guarda los avisos de cada usuario y el enlace que abrirá desde el menú.
create table if not exists public.notificaciones (
    id bigint generated by default as identity primary key,
    usuario_id uuid not null references public.perfiles(id) on delete cascade,
    titulo text not null,
    detalle text not null,
    enlace text not null,
    leida boolean not null default false,
    creado_en timestamptz not null default now()
);

-- Completa una tabla previa con el esquema actual sin borrar sus notificaciones.
-- CREATE TABLE IF NOT EXISTS no agrega columnas cuando la tabla ya existe.
alter table public.notificaciones
    add column if not exists id bigint generated by default as identity,
    add column if not exists usuario_id uuid references public.perfiles(id) on delete cascade,
    add column if not exists titulo text not null default 'Notificación',
    add column if not exists detalle text not null default '',
    add column if not exists enlace text not null default '/',
    add column if not exists leida boolean not null default false,
    add column if not exists creado_en timestamptz not null default now();

-- La tabla anterior podía exigir "mensaje"; el sistema nuevo usa titulo y detalle.
-- Conserva los mensajes antiguos, pero permite NULL en filas creadas por los nuevos triggers.
do $$
begin
    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'notificaciones'
          and column_name = 'mensaje'
          and is_nullable = 'NO'
    ) then
        alter table public.notificaciones alter column mensaje drop not null;
    end if;
end;
$$;

create index if not exists notificaciones_usuario_fecha_idx
    on public.notificaciones (usuario_id, creado_en desc);

-- La sesión solo puede leer sus filas y cambiar únicamente su marca de lectura.
alter table public.notificaciones enable row level security;
revoke all on public.notificaciones from anon, authenticated;
grant select on public.notificaciones to authenticated;
grant update (leida) on public.notificaciones to authenticated;

drop policy if exists "notificaciones_leer_propias" on public.notificaciones;
create policy "notificaciones_leer_propias"
on public.notificaciones for select to authenticated
using (usuario_id = auth.uid());

drop policy if exists "notificaciones_marcar_propias" on public.notificaciones;
create policy "notificaciones_marcar_propias"
on public.notificaciones for update to authenticated
using (usuario_id = auth.uid())
with check (usuario_id = auth.uid());

-- Crea el enlace correcto para el panel del destinatario e inserta el aviso.
create or replace function public.registrar_notificacion(
    p_usuario_id uuid,
    p_servicio_id bigint,
    p_titulo text,
    p_detalle text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_rol text;
    v_enlace text;
begin
    if p_usuario_id is null then
        return;
    end if;

    select rol into v_rol from public.perfiles where id = p_usuario_id;
    v_enlace := case v_rol
        when 'cliente' then '/cliente/solicitudes/' || p_servicio_id::text
        when 'tecnico' then '/tecnico/servicios/' || p_servicio_id::text
        when 'admin' then '/admin/servicios/' || p_servicio_id::text
        else '/'
    end;

    insert into public.notificaciones (usuario_id, titulo, detalle, enlace)
    values (p_usuario_id, p_titulo, p_detalle, v_enlace);
end;
$$;

-- Copia avisos operativos a los administradores para que puedan supervisarlos.
create or replace function public.notificar_administradores(
    p_servicio_id bigint,
    p_titulo text,
    p_detalle text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_admin_id uuid;
begin
    for v_admin_id in
        select id from public.perfiles
        where rol = 'admin' and id is distinct from auth.uid()
    loop
        perform public.registrar_notificacion(v_admin_id, p_servicio_id, p_titulo, p_detalle);
    end loop;
end;
$$;

-- Avisa a cliente y técnico cuando se asigna o cambia el técnico responsable.
create or replace function public.notificar_asignacion_servicio()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if tg_op = 'INSERT' then
        if new.tecnico_id is not null then
            perform public.registrar_notificacion(
                new.cliente_id, new.id, 'Técnico asignado',
                'Un técnico fue asignado a tu servicio.'
            );
            perform public.registrar_notificacion(
                new.tecnico_id, new.id, 'Nuevo servicio asignado',
                'Tienes un servicio nuevo para atender.'
            );
            perform public.notificar_administradores(
                new.id, 'Técnico asignado',
                'Se asignó un técnico al servicio.'
            );
        end if;
        return new;
    end if;

    if new.tecnico_id is not null and old.tecnico_id is distinct from new.tecnico_id then
        perform public.registrar_notificacion(
            new.cliente_id, new.id, 'Técnico asignado',
            'Un técnico fue asignado a tu servicio.'
        );
        perform public.registrar_notificacion(
            new.tecnico_id, new.id, 'Nuevo servicio asignado',
            'Tienes un servicio nuevo para atender.'
        );
        perform public.notificar_administradores(
            new.id, 'Técnico asignado',
            'Se asignó un técnico al servicio.'
        );
    end if;
    return new;
end;
$$;

-- Avisa a los participantes cuando cambia el estado del servicio.
create or replace function public.notificar_cambio_estado_servicio()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if old.estado is distinct from new.estado then
        -- El aviso de asignación ya comunica el paso inicial a "asignado".
        if not (old.tecnico_id is distinct from new.tecnico_id and new.estado = 'asignado')
           and new.estado <> 'cotizado'
           and not (
               new.cliente_id = auth.uid()
               and new.estado in ('aprobado', 'en_diagnostico')
           ) then
            if new.cliente_id is distinct from auth.uid() then
                perform public.registrar_notificacion(
                    new.cliente_id, new.id, 'Estado del servicio actualizado',
                    'El servicio ahora está en estado: ' || replace(new.estado::text, '_', ' ') || '.'
                );
            end if;
            if new.tecnico_id is not null and new.tecnico_id is distinct from auth.uid() then
                perform public.registrar_notificacion(
                    new.tecnico_id, new.id, 'Estado del servicio actualizado',
                    'El servicio ahora está en estado: ' || replace(new.estado::text, '_', ' ') || '.'
                );
            end if;
            perform public.notificar_administradores(
                new.id, 'Estado del servicio actualizado',
                'El servicio ahora está en estado: ' || replace(new.estado::text, '_', ' ') || '.'
            );
        end if;
    end if;
    return new;
end;
$$;

-- Informa al cliente que ya puede revisar la cotización enviada.
create or replace function public.notificar_cotizacion_creada()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_cliente_id uuid;
begin
    select cliente_id into v_cliente_id from public.servicios where id = new.servicio_id;
    perform public.registrar_notificacion(
        v_cliente_id, new.servicio_id, 'Nueva cotización',
        'El técnico preparó una cotización para tu servicio.'
    );
    perform public.notificar_administradores(
        new.servicio_id, 'Nueva cotización',
        'Se creó una cotización para este servicio.'
    );
    return new;
end;
$$;

-- Informa al técnico cuando el cliente aprueba o rechaza su cotización.
create or replace function public.notificar_respuesta_cotizacion()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_tecnico_id uuid;
    v_respuesta text;
begin
    if old.estado is distinct from new.estado and new.estado in ('aprobada', 'rechazada') then
        select tecnico_id into v_tecnico_id from public.servicios where id = new.servicio_id;
        v_respuesta := case new.estado when 'aprobada' then 'aprobó' else 'rechazó' end;
        perform public.registrar_notificacion(
            v_tecnico_id, new.servicio_id, 'Respuesta a la cotización',
            'El cliente ' || v_respuesta || ' la cotización.'
        );
        perform public.notificar_administradores(
            new.servicio_id, 'Respuesta a la cotización',
            'El cliente ' || v_respuesta || ' la cotización.'
        );
    end if;
    return new;
end;
$$;

-- Avisa a los demás participantes cuando se publica un mensaje en el chat.
create or replace function public.notificar_mensaje_servicio()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_servicio public.servicios%rowtype;
begin
    select * into v_servicio from public.servicios where id = new.servicio_id;
    if v_servicio.cliente_id is distinct from new.autor_id then
        perform public.registrar_notificacion(
            v_servicio.cliente_id, new.servicio_id, 'Nuevo mensaje',
            'Hay un mensaje nuevo en la conversación del servicio.'
        );
    end if;
    if v_servicio.tecnico_id is not null and v_servicio.tecnico_id is distinct from new.autor_id then
        perform public.registrar_notificacion(
            v_servicio.tecnico_id, new.servicio_id, 'Nuevo mensaje',
            'Hay un mensaje nuevo en la conversación del servicio.'
        );
    end if;
    perform public.notificar_administradores(
        new.servicio_id, 'Nuevo mensaje',
        'Hay un mensaje nuevo en la conversación del servicio.'
    );
    return new;
end;
$$;

-- Registra avisos al asignar técnico, cambiar estado, cotizar, responder o escribir.
drop trigger if exists trg_notificar_asignacion_servicio on public.servicios;
create trigger trg_notificar_asignacion_servicio
after insert or update on public.servicios
for each row execute function public.notificar_asignacion_servicio();

drop trigger if exists trg_notificar_cambio_estado_servicio on public.servicios;
create trigger trg_notificar_cambio_estado_servicio
after update on public.servicios
for each row execute function public.notificar_cambio_estado_servicio();

drop trigger if exists trg_notificar_cotizacion_creada on public.cotizaciones;
create trigger trg_notificar_cotizacion_creada
after insert on public.cotizaciones
for each row execute function public.notificar_cotizacion_creada();

drop trigger if exists trg_notificar_respuesta_cotizacion on public.cotizaciones;
create trigger trg_notificar_respuesta_cotizacion
after update on public.cotizaciones
for each row execute function public.notificar_respuesta_cotizacion();

drop trigger if exists trg_notificar_mensaje_servicio on public.mensajes_servicio;
create trigger trg_notificar_mensaje_servicio
after insert on public.mensajes_servicio
for each row execute function public.notificar_mensaje_servicio();

-- Solo los triggers pueden crear notificaciones; la clave pública no puede invocar helpers.
revoke execute on function public.registrar_notificacion(uuid, bigint, text, text) from public, anon, authenticated;
revoke execute on function public.notificar_administradores(bigint, text, text) from public, anon, authenticated;
revoke execute on function public.notificar_asignacion_servicio() from public, anon, authenticated;
revoke execute on function public.notificar_cambio_estado_servicio() from public, anon, authenticated;
revoke execute on function public.notificar_cotizacion_creada() from public, anon, authenticated;
revoke execute on function public.notificar_respuesta_cotizacion() from public, anon, authenticated;
revoke execute on function public.notificar_mensaje_servicio() from public, anon, authenticated;

-- Activa eventos INSERT/UPDATE de notificaciones para el canal Realtime del usuario.
do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'notificaciones'
    ) then
        alter publication supabase_realtime add table public.notificaciones;
    end if;
end;
$$;

comment on table public.notificaciones is 'Avisos privados que llevan a los usuarios al detalle de un servicio.';
