-- =====================================================================
-- mensajes_servicio.sql
-- Conversación por servicio, protegida por RLS y lista para Realtime.
-- El administrador tiene lectura; solo cliente y técnico pueden escribir.
-- Ejecutar en Supabase → SQL Editor. Puede ejecutarse varias veces.
-- =====================================================================

create table if not exists public.mensajes_servicio (
    id bigint generated by default as identity primary key,
    servicio_id bigint not null references public.servicios(id) on delete cascade,
    autor_id uuid not null references public.perfiles(id) on delete restrict,
    texto text not null check (char_length(btrim(texto)) between 1 and 500),
    creado_en timestamptz not null default now()
);

create index if not exists mensajes_servicio_servicio_creado_idx
    on public.mensajes_servicio (servicio_id, creado_en);

alter table public.mensajes_servicio enable row level security;
revoke all on public.mensajes_servicio from anon, authenticated;
grant select, insert on public.mensajes_servicio to authenticated;
grant usage, select on sequence public.mensajes_servicio_id_seq to authenticated;

drop policy if exists "mensajes_servicio_leer_participantes" on public.mensajes_servicio;
create policy "mensajes_servicio_leer_participantes"
on public.mensajes_servicio for select to authenticated
using (
    exists (
        select 1
        from public.servicios as servicio
        where servicio.id = mensajes_servicio.servicio_id
          and (
              servicio.cliente_id = auth.uid()
              or servicio.tecnico_id = auth.uid()
              or public.rol_actual() = 'admin'
          )
    )
);

drop policy if exists "mensajes_servicio_escribir_participantes" on public.mensajes_servicio;
create policy "mensajes_servicio_escribir_participantes"
on public.mensajes_servicio for insert to authenticated
with check (
    autor_id = auth.uid()
    and exists (
        select 1
        from public.servicios as servicio
        where servicio.id = mensajes_servicio.servicio_id
          and (
              servicio.cliente_id = auth.uid()
              or servicio.tecnico_id = auth.uid()
          )
    )
);

-- Realtime requiere que la tabla pertenezca a la publicación. Evita duplicarla.
do $$
begin
    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'mensajes_servicio'
    ) then
        alter publication supabase_realtime add table public.mensajes_servicio;
    end if;
end;
$$;

comment on table public.mensajes_servicio is 'Mensajes inmutables entre participantes de un servicio TecnoHouse.';
